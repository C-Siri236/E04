# 列表合并。将两个有序列表合并为一个有序列表。
# 例如，列表[1, 4, 7, 12, 20]和列表[10, 15, 17, 33]
# 合并为[1, 4, 7, 10, 12, 15, 17, 20, 33]，
# 列表[2, 3, 5, 7]和列表[11, 13, 17]合并为[2, 3, 5, 7, 11, 13, 17]，
# 列表[2, 3, 5, 7, 11]和列表[7, 11, 13, 17]
# 合并为[2, 3, 5, 7, 7, 11, 11, 13, 17]，
# 列表[1, 2, 3]和列表[]合并为[1, 2, 3]。
import ast

a = ast.literal_eval(input("输入列表: "))
b = ast.literal_eval(input("输入列表: "))

result = sorted(a + b)
print(result)